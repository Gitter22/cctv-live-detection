import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import type { EdgeConfig } from '@cctv/shared';
import { stringify } from 'yaml';
import { logger } from './logger';

/**
 * vision.yaml for services/vision. Vision reads go2rtc's local streams (no credentials here)
 * and hot-reloads this file; only cameras whose settings changed are restarted.
 */
export function renderVisionYaml(config: EdgeConfig, opts: { go2rtcRtsp: string; modelPath?: string }): string {
  const doc = {
    detector: { type: 'dfine', model_path: opts.modelPath ?? '/models/dfine.onnx', input_size: 640 },
    cameras: config.cameras
      .filter((c) => c.enabled)
      .map((c) => ({
        id: c.key,
        name: c.label,
        url: `${opts.go2rtcRtsp.replace(/\/$/, '')}/${c.key}`,
        classes: c.detection.classes,
        confidence: c.detection.confidence,
        low_confidence: c.detection.lowConfidence,
        detect_fps: c.detection.detectFps,
        motion_gate: c.detection.motionGate,
        zones: c.zones.map((z) => ({ id: z.key, polygon: z.polygon })),
        lines: c.lines.map((l) => ({ id: l.key, start: l.start, end: l.end })),
      })),
  };
  return `# GENERATED by the edge agent from the server config (site: ${config.site.slug}). Do not edit.\n${stringify(doc)}`;
}

/** Write vision.yaml if its content changed. Returns true if written. */
export async function applyVision(config: EdgeConfig, opts: { path: string; go2rtcRtsp: string }): Promise<boolean> {
  const text = renderVisionYaml(config, opts);
  try {
    if ((await readFile(opts.path, 'utf8')) === text) return false;
  } catch {
    // first write
  }
  await mkdir(dirname(opts.path), { recursive: true });
  const tmp = `${opts.path}.tmp`;
  await writeFile(tmp, text);
  await rename(tmp, opts.path); // atomic: vision never reads a half-written file
  logger.info({ cameras: config.cameras.filter((c) => c.enabled).map((c) => c.key) }, 'vision config written');
  return true;
}
