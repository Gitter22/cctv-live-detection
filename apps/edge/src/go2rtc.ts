import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import type { EdgeConfig } from '@cctv/shared';
import { parse, stringify } from 'yaml';
import { logger } from './logger';

/**
 * go2rtc is the only component that talks to cameras/NVRs. The edge writes its config
 * (one stream per camera: <key> = sub stream, <key>_main = main stream) and asks go2rtc
 * to restart, but only when the stream list actually changed (a restart drops live viewers).
 */
export function go2rtcStreams(config: EdgeConfig): Record<string, string> {
  const streams: Record<string, string> = {};
  for (const c of config.cameras) {
    if (!c.enabled) continue;
    streams[c.key] = c.streams.sub;
    if (c.streams.main) streams[`${c.key}_main`] = c.streams.main;
    // H.264 copy for browsers without H.265 WebRTC; go2rtc only transcodes while someone watches.
    streams[`${c.key}_h264`] = `ffmpeg:${c.key}#video=h264`;
  }
  return streams;
}

export function renderGo2rtcYaml(config: EdgeConfig, webrtc: { candidates?: string[]; iceServers?: unknown[] } = {}): string {
  const doc = {
    streams: go2rtcStreams(config),
    api: { listen: ':1984' },
    rtsp: { listen: ':8554' },
    // candidates: addresses viewers can reach go2rtc at (go2rtc runs in Docker, its own IP isn't
    // reachable). "stun:8555" = discover the public address via STUN for remote viewers.
    webrtc: { listen: ':8555', ...(webrtc.candidates?.length ? { candidates: webrtc.candidates } : {}), ...(webrtc.iceServers?.length ? { ice_servers: webrtc.iceServers } : {}) },
    log: { level: 'info' },
  };
  return (
    '# GENERATED by the edge agent from the server config. Do not edit: changes are overwritten.\n' +
    `# site: ${config.site.slug}\n` +
    stringify(doc, { lineWidth: 0 })
  );
}

export interface Go2rtcApplyOptions {
  path: string;
  apiUrl: string;
  fetchImpl?: typeof fetch;
  webrtc?: { candidates?: string[]; iceServers?: unknown[] };
}

/** Write the config if streams changed and restart go2rtc. Returns true if go2rtc was restarted. */
export async function applyGo2rtc(config: EdgeConfig, opts: Go2rtcApplyOptions): Promise<boolean> {
  const wanted = go2rtcStreams(config);
  let current: Record<string, string> | null = null;
  try {
    current = ((parse(await readFile(opts.path, 'utf8')) as { streams?: Record<string, string> } | null)?.streams ?? {}) as Record<string, string>;
  } catch {
    // no file yet
  }
  const text = renderGo2rtcYaml(config, opts.webrtc);
  let currentText = '';
  try {
    currentText = await readFile(opts.path, 'utf8');
  } catch {
    // none
  }
  if (current && sameStreams(current, wanted) && currentText === text) return false;

  await mkdir(dirname(opts.path), { recursive: true });
  const tmp = `${opts.path}.tmp`;
  // Contains camera credentials: owner-only permissions.
  await writeFile(tmp, text, { mode: 0o600 });
  await rename(tmp, opts.path);
  logger.info({ streams: Object.keys(wanted) }, 'go2rtc config written');

  try {
    const res = await (opts.fetchImpl ?? fetch)(`${opts.apiUrl}/api/restart`, { method: 'POST', signal: AbortSignal.timeout(5000) });
    logger.info({ status: res.status }, 'go2rtc restart requested');
    return res.ok;
  } catch (err) {
    // Not running yet: it reads the new file when it starts.
    logger.warn({ err: (err as Error).message }, 'go2rtc not reachable for restart');
    return false;
  }
}

function sameStreams(a: Record<string, string>, b: Record<string, string>) {
  const ka = Object.keys(a).sort();
  const kb = Object.keys(b).sort();
  return ka.length === kb.length && ka.every((k, i) => k === kb[i] && a[k] === b[k]);
}
